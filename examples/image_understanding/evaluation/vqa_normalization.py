_COMMA_BETWEEN_DIGITS = re.compile(r"\d,\d")
_PERIOD_BEFORE_NO_DIGIT = re.compile(r"\.(?!\d)")


def normalize_vqa_answer(answer: str) -> str:
    """``answer`` in the form VQA accuracy compares.

    Newlines and tabs become spaces and surrounding whitespace is dropped. Each
    mark of ``PUNCTUATION`` is then deleted throughout the answer when one of its
    occurrences touches a space, or when the answer holds a comma between two
    digits; otherwise every occurrence becomes a space. A period is deleted unless
    a digit follows it, for the first ``MAX_PERIODS_REMOVED`` such periods. The
    answer is lowercased and split into words: a word of ``NUMBER_WORDS`` becomes
    its digits, the ``ARTICLES`` are dropped, a word of ``CONTRACTIONS`` gets its
    apostrophe, and the words are joined by single spaces. Apostrophes and colons
    are kept, so a possessive stays one and a time of day stays readable.
    """
    text = answer.replace("\n", " ").replace("\t", " ").strip()
    deletes_every_mark = _COMMA_BETWEEN_DIGITS.search(text) is not None
    unmarked = text
    for mark in PUNCTUATION:
        deleted = deletes_every_mark or f"{mark} " in text or f" {mark}" in text
        unmarked = unmarked.replace(mark, "" if deleted else " ")
    unmarked = _PERIOD_BEFORE_NO_DIGIT.sub("", unmarked, count=MAX_PERIODS_REMOVED)
    words = (NUMBER_WORDS.get(word, word) for word in unmarked.lower().split())
    return " ".join(CONTRACTIONS.get(word, word) for word in words if word not in ARTICLES)
